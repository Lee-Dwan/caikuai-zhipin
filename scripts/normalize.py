def norm_province(raw):
    if not raw:
        return ""
    s = PROVINCE_ALIASES.get(str(raw).strip(), str(raw).strip())
    for p in _PROVINCES:
        if s == p or s.startswith(p):
            return p
    return ""


TRAD_CITY = {"桃園": "桃园", "臺北": "台北", "臺中": "台中", "臺南": "台南", "高雄": "高雄", "新竹": "新竹"}
NO_CITY = {"共享中心", "全国", "不限", "其他"}


def normalize_city(raw):
    """返回 (城市, 省份)。输入可能是「北京市」「杭州」「浙江省·杭州市」等。"""
    if not raw:
        return "", ""
    if str(raw).strip() in NO_CITY:
        return "", ""
    s = str(raw).strip().replace(" ", "")
    s = re.sub(r"^(中国|中国大陆|China)[·\-—/]?", "", s, flags=re.I)
    s = re.sub(r"[·\-—/|]+", "·", s)
    city, prov = "", ""
    for part in [p for p in s.split("·") if p]:
        p2 = re.sub(r"市$", "", part)
        p2 = re.sub(r"(省|自治区|特别行政区)$", "", p2)
        if p2 in CITY_TO_PROVINCE:
            city, prov = p2, CITY_TO_PROVINCE[p2]
        elif norm_province(part):
            prov = norm_province(part)
    if city:
        return TRAD_CITY.get(city, city), prov
    for name in sorted(CITY_TO_PROVINCE, key=len, reverse=True):
        if name in s:
            return name, CITY_TO_PROVINCE[name]
    return "", norm_province(s)


