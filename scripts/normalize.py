def extract_certs(text):
    if not text:
        return ["不限"]
    found = [name for name, pats in CERT_RULES if any(re.search(p, text, flags=re.I) for p in pats)]
    return found or ["不限"]


_WS = re.compile(r"[ \t\u3000]+")


def clean_text(text, limit=None):
    if text is None:
        return ""
    s = str(text).replace("\r", "")
    s = re.sub(r"<br\s*/?>", "\n", s, flags=re.I)
    s = re.sub(r"<[^>]+>", "", s)
    s = s.replace("&nbsp;", " ").replace("&amp;", "&").replace("&lt;", "<").replace("&gt;", ">")
    s = "\n".join(_WS.sub(" ", line).strip() for line in s.split("\n"))
    s = re.sub(r"\n{3,}", "\n\n", s).strip()
    if limit and len(s) > limit:
        s = s[:limit].rstrip() + "…"
    return s


LABEL_RE = re.compile(r"^(岗位职责|职位职责|职位描述|工作职责|主要职责|岗位描述)[:：]\s*")


def summarize(text, limit=90):
    s = clean_text(text).replace("\n", " ")
    s = LABEL_RE.sub("", s)
    s = re.sub(r"^[1-9][.、]\s*", "", s)
    if len(s) > limit:
        s = s[:limit].rstrip("，,。；; ") + "…"
    return s


def make_id(firm_id, title, city, url=""):
    key = f"{firm_id}|{re.sub(r'[^0-9A-Za-z\u4e00-\u9fa5]', '', title)}|{city}"
    if url:
        key += "|" + url
    return hashlib.sha1(key.encode("utf-8")).hexdigest()[:12]
